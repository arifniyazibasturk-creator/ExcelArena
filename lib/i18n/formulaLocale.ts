// Normalize names for mapping
function normalizeName(name: string): string {
  return name
    .trim()
    .toUpperCase()
    .replace(/İ/g, "I")
    .replace(/ı/g, "I")
    .replace(/Ş/g, "S")
    .replace(/Ğ/g, "G")
    .replace(/Ü/g, "U")
    .replace(/Ö/g, "O")
    .replace(/Ç/g, "C");
}

const NAME_TO_CANONICAL: Map<string, CanonicalFunctionId> = new Map();

// Populate mapping
Object.values(FORMULA_DEFINITIONS).forEach((def) => {
  NAME_TO_CANONICAL.set(def.canonical.toUpperCase(), def.canonical);
  NAME_TO_CANONICAL.set(def.en.toUpperCase(), def.canonical);
  NAME_TO_CANONICAL.set(def.tr.toUpperCase(), def.canonical);
  NAME_TO_CANONICAL.set(normalizeName(def.tr), def.canonical);

  if (def.trAliases) {
    def.trAliases.forEach((alias) => {
      NAME_TO_CANONICAL.set(alias.toUpperCase(), def.canonical);
      NAME_TO_CANONICAL.set(normalizeName(alias), def.canonical);
    });
  }
});

export function resolveToCanonicalFunction(name: string): CanonicalFunctionId | null {
  const upper = name.trim().toUpperCase();
  if (NAME_TO_CANONICAL.has(upper)) {
    return NAME_TO_CANONICAL.get(upper)!;
  }
  const norm = normalizeName(name);
  if (NAME_TO_CANONICAL.has(norm)) {
    return NAME_TO_CANONICAL.get(norm)!;
  }
  return null;
}

export function getLocalizedFunctionName(
  canonical: CanonicalFunctionId,
  locale: ResolvedFormulaLocale
): string {
  const def = FORMULA_DEFINITIONS[canonical];
  if (!def) return canonical;
  return locale === "tr" ? def.tr : def.en;
}

export function getLocalizedSyntax(
  canonical: CanonicalFunctionId,
  locale: ResolvedFormulaLocale
): string {
  const def = FORMULA_DEFINITIONS[canonical];
  if (!def) return `=${canonical}(...)`;
  return locale === "tr" ? def.syntaxTr : def.syntaxEn;
}
